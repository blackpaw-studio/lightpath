func gen(t *testing.T) string {
	t.Helper()
	var buf bytes.Buffer
	carriers := []Carrier{{Code: "chcgil", City: "Chicago", Lat: 41.88, Lon: -87.63}}
	metros := []Carrier{{Code: "nyc", City: "New York", Lat: 40.71, Lon: -74.01}}
	if err := Generate(strings.NewReader(sampleCSV), carriers, metros, &buf); err != nil {
		t.Fatalf("Generate: %v", err)
	}
	return buf.String()
}

func TestGenerateKeepsOnlyScheduledLargeAndMediumWithIATA(t *testing.T) {
	out := gen(t)
	for _, want := range []string{`"ord":`, `"fra":`, `"smv":`, `"chcgil":`, "var metroHints", `"nyc":`} {
		if !strings.Contains(out, want) {
			t.Errorf("output missing %s", want)
		}
	}
	for _, bad := range []string{`"tny"`, `"hli"`, `"toolong"`, `"qtv"`, "Dupe Medium"} {
		if strings.Contains(out, bad) {
			t.Errorf("output must not contain %s", bad)
		}
	}
}

func TestGenerateRoundsAndUsesMunicipality(t *testing.T) {
	out := gen(t)
	if !strings.Contains(out, `"ord": {Lat: 41.98, Lon: -87.9, City: "Chicago"}`) {
		t.Errorf("unexpected ORD entry:\n%s", out)
	}
	if !strings.Contains(out, `City: "Frankfurt am Main"`) {
		t.Error("municipality should be the city")
	}
}

func TestGenerateIsValidGoAndDeterministic(t *testing.T) {
	out := gen(t)
	if _, err := parser.ParseFile(token.NewFileSet(), "hints_table.go", out, 0); err != nil {
		t.Fatalf("generated code does not parse: %v", err)
	}
	if !strings.HasPrefix(out, "// Code generated by tools/genhints; DO NOT EDIT.") {
		t.Error("missing generated-code header")
	}
	if gen(t) != out {
		t.Error("output is not deterministic")
	}
}

func TestGenerateRejectsMissingColumns(t *testing.T) {
	err := Generate(strings.NewReader("a,b\n1,2\n"), nil, nil, &bytes.Buffer{})
	if err == nil {
		t.Error("expected an error for a CSV without the expected columns")
	}
}

func TestCuratedCarrierCodesAreWellFormed(t *testing.T) {
	seen := map[string]bool{}
	for _, c := range carrierCodes {
		if len(c.Code) != 6 || c.Code != strings.ToLower(c.Code) {
			t.Errorf("carrier code %q must be 6 lowercase chars", c.Code)
		}
		if seen[c.Code] {
			t.Errorf("duplicate carrier code %q", c.Code)
		}
		seen[c.Code] = true
		if c.Lat < -90 || c.Lat > 90 || c.Lon < -180 || c.Lon > 180 || c.City == "" {
			t.Errorf("carrier %q has bad data: %+v", c.Code, c)
		}
	}
}

