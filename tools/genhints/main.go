// Command genhints generates internal/enrich/hints_table.go from the
// OurAirports airports.csv (public domain, https://ourairports.com/data/) and
// the curated carrier city codes in carriers.go.
//
//	go run ./tools/genhints -in airports.csv -out internal/enrich/hints_table.go
//
// With no -in it downloads the data from the OurAirports GitHub mirror.
package main

import (
	"encoding/csv"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
)

const defaultSource = "https://davidmegginson.github.io/ourairports-data/airports.csv"

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "genhints:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	fs := flag.NewFlagSet("genhints", flag.ContinueOnError)
	in := fs.String("in", defaultSource, "airports.csv path or http(s) URL")
	out := fs.String("out", "hints_table.go", "output file")
	if err := fs.Parse(args); err != nil {
		return err
	}
	r, err := open(*in)
	if err != nil {
		return err
	}
	defer r.Close()
	var buf strings.Builder
	if err := Generate(r, carrierCodes, metroCodes, &buf); err != nil {
		return err
	}
	return os.WriteFile(*out, []byte(buf.String()), 0o644)
}

func open(src string) (io.ReadCloser, error) {
	if !strings.HasPrefix(src, "http://") && !strings.HasPrefix(src, "https://") {
		return os.Open(src)
	}
	client := &http.Client{Timeout: 60 * time.Second}
	resp, err := client.Get(src)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		resp.Body.Close()
		return nil, fmt.Errorf("GET %s: %s", src, resp.Status)
	}
	return resp.Body, nil
}

type airport struct {
	iata     string
	lat, lon float64
	city     string
	rank     int // lower is better when two airports share an IATA code
}

// Generate reads OurAirports CSV from r and writes the Go source of the hint
// tables (large and medium airports with an IATA code and scheduled service,
// plus curated carrier and metro codes) to w.
func Generate(r io.Reader, carriers, metros []Carrier, w io.Writer) error {
	airports, err := readAirports(r)
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("// Code generated by tools/genhints; DO NOT EDIT.\n")
	b.WriteString("// Airport data: OurAirports, public domain, https://ourairports.com/data/\n\n")
	b.WriteString("package enrich\n\n")
	b.WriteString("// iataHints maps lowercase IATA airport codes to their city.\n")
	b.WriteString("var iataHints = map[string]Hint{\n")
	for _, a := range airports {
		fmt.Fprintf(&b, "\t%q: {Lat: %s, Lon: %s, City: %q},\n", a.iata, num(a.lat), num(a.lon), a.city)
	}
	b.WriteString("}\n\n")
	writeCurated(&b, "carrierHints", "curated 6-character carrier city codes", carriers)
	b.WriteString("\n")
	writeCurated(&b, "metroHints", "curated 3-letter metro codes", metros)
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	_, err = w.Write(src)
	return err
}

func writeCurated(b *strings.Builder, name, what string, entries []Carrier) {
	fmt.Fprintf(b, "// %s maps %s to their city.\n", name, what)
	fmt.Fprintf(b, "var %s = map[string]Hint{\n", name)
	sorted := append([]Carrier(nil), entries...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Code < sorted[j].Code })
	for _, c := range sorted {
		fmt.Fprintf(b, "\t%q: {Lat: %s, Lon: %s, City: %q},\n", c.Code, num(c.Lat), num(c.Lon), c.City)
	}
	b.WriteString("}\n")
}

// num formats a coordinate rounded to two decimals (~1 km) without trailing zeros.
func num(f float64) string {
	return strconv.FormatFloat(roundTo2(f), 'f', -1, 64)
}

func roundTo2(f float64) float64 {
	v, _ := strconv.ParseFloat(strconv.FormatFloat(f, 'f', 2, 64), 64)
	return v
}

func readAirports(r io.Reader) ([]airport, error) {
	cr := csv.NewReader(r)
	cr.FieldsPerRecord = -1
	header, err := cr.Read()
	if err != nil {
		return nil, fmt.Errorf("read header: %w", err)
	}
	col := map[string]int{}
	for i, h := range header {
		col[h] = i
	}
	for _, need := range []string{"type", "latitude_deg", "longitude_deg", "municipality", "name", "iata_code", "scheduled_service"} {
		if _, ok := col[need]; !ok {
			return nil, fmt.Errorf("airports csv has no %q column", need)
		}
	}
	best := map[string]airport{}
	for {
		rec, err := cr.Read()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, err
		}
		a, ok := parseAirport(rec, col)
		if !ok {
			continue
		}
		if cur, dup := best[a.iata]; !dup || a.rank < cur.rank {
			best[a.iata] = a
		}
	}
	out := make([]airport, 0, len(best))
	for _, a := range best {
		out = append(out, a)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].iata < out[j].iata })
	return out, nil
}

func parseAirport(rec []string, col map[string]int) (airport, bool) {
	get := func(name string) string {
		if i := col[name]; i < len(rec) {
			return strings.TrimSpace(rec[i])
		}
		return ""
	}
	rank := 0
	switch get("type") {
	case "large_airport":
	case "medium_airport":
		rank = 1
	default:
		return airport{}, false
	}
	iata := strings.ToLower(get("iata_code"))
	if len(iata) != 3 || strings.Trim(iata, "abcdefghijklmnopqrstuvwxyz") != "" {
		return airport{}, false
	}
	lat, err1 := strconv.ParseFloat(get("latitude_deg"), 64)
	lon, err2 := strconv.ParseFloat(get("longitude_deg"), 64)
	if err1 != nil || err2 != nil {
		return airport{}, false
	}
	city := get("municipality")
	if city == "" {
		city = get("name")
	}
	if get("scheduled_service") != "yes" {
		return airport{}, false // keeps the table to airports with airline service
	}
	return airport{iata: iata, lat: lat, lon: lon, city: city, rank: rank}, true
}
